/**
 * ConvAI MVP — Response Composer
 * 
 * Composes the final response to the user based on policy decisions,
 * LLM outputs, and intent classifications.
 */

const logger = require('../utils/logger');
const { intentClassifier } = require('./intentClassifier'); // Assuming intentClassifier is available
const { extractThinking } = require('../utils/llmUtils'); // To parse LLM output

// Define score ranges based on policy decisions for deterministic scoring
const POLICY_SCORE_MAP = {
  'PROCEED': 95, // High confidence for unrestricted access
  'PROCEED_WITH_CONDITIONS': 80, // Medium confidence, some restrictions applied
  'BLOCK': 0, // No access granted
  'REDACT': 0, // Content blocked, but action might be allowed with redaction. Score could be higher if action is allowed. For now, assuming blocked content means low score for this purpose.
};

// Score for LLM generation quality/confidence (can be refined)
const LLM_GENERATION_CONFIDENCE_SCORE = 90; // Default high confidence if LLM output is good

class ResponseComposer {
  /**
   * Composes the final user response.
   * 
   * @param {object} policyResult - The result from OPA policy evaluation.
   * @param {object} intentResult - The result from intent classification.
   * @param {string} rawLlmResponse - The raw text generated by the LLM.
   * @param {string} channel - The communication channel (e.g., 'whatsapp').
   * @param {boolean} devModeEnabled - Whether developer mode is active.
   * @param {string} reasoning - Chain-of-thought reasoning from LLM.
   * @param {object} authContext - Debugging context for auth/policy.
   * @param {object} policyInputDebug - Debugging input sent to OPA.
   * 
   * @returns {{finalResponse: string, wasBlocked: boolean, policyDecision: string, score: number, rationale: string}}
   */
  compose(policyResult, intentResult, rawLlmResponse, channel, devModeEnabled, reasoning, authContext, policyInputDebug) {
    let finalResponse = '';
    let wasBlocked = false;
    let policyDecision = policyResult.decision;

    // Determine the primary score and rationale
    let score = 0;
    let rationale = 'No specific rationale available.';

    // --- Score and Rationale Derivation ---

    // 1. Score and Rationale from Policy Result (if available and relevant)
    if (policyResult && policyResult.decision) {
      policyDecision = policyResult.decision; // Use OPA's decision
      
      // Assign score based on policy outcome
      score = POLICY_SCORE_MAP[policyDecision] || 0;

      // Construct rationale from policy details
      let policyRationaleParts = [];
      if (policyResult.reason) {
        policyRationaleParts.push(`Policy Reason: ${policyResult.reason}`);
      }
      if (policyResult.conditions && policyResult.conditions.length > 0) {
        policyRationaleParts.push(`Policy Conditions Applied: ${policyResult.conditions.join(', ')}`);
      }
      if (policyResult.rationale_code) {
        policyRationaleParts.push(`Rationale Code: ${policyResult.rationale_code}`);
      }
      
      // If policy result has specific rationale, use it. Otherwise, use default reasons.
      if (policyRationaleParts.length > 0) {
        rationale = policyRationaleParts.join('; ');
      } else {
        rationale = `Policy outcome: ${policyDecision}.`;
      }

      if (policyDecision === 'BLOCK') {
        wasBlocked = true;
        finalResponse = policyResult.reason || 'Your request has been blocked due to policy restrictions.';
      } else if (policyDecision === 'REDACT') {
        finalResponse = policyResult.redacted_text || 'Response requires redaction.';
        wasBlocked = false; // Content is modified, but request is processed
        // Adjust score for redaction if needed, e.g., slightly lower if critical info is removed.
        // For now, keep score from policyOutcome.
      }
    } else {
      // Default if no policy result (should not happen with fail-closed)
      policyDecision = 'BLOCK';
      wasBlocked = true;
      finalResponse = 'An unexpected error occurred, and your request could not be processed.';
      score = 0;
      rationale = 'No policy decision was returned.';
    }

    // 2. Incorporate LLM's generated score and rationale, or LLM-specific additions
    let llmGeneratedScore = null;
    let llmGeneratedRationale = null;
    let llmCleanResponse = rawLlmResponse; // Default to raw response

    if (rawLlmResponse) {
      try {
        // Attempt to parse score and rationale from LLM output
        // This assumes LLM follows the prompt instructions for "Score: X" and "Rationale: Y"
        const scoreMatch = rawLlmResponse.match(/Score:\s*(\d+)/i);
        if (scoreMatch && scoreMatch[1]) {
          llmGeneratedScore = parseInt(scoreMatch[1], 10);
        }

        const rationaleMatch = rawLlmResponse.match(/Rationale:\s*(.*)/is); // 's' flag for dotall, 'i' for case-insensitive
        if (rationaleMatch && rationaleMatch[1]) {
          llmGeneratedRationale = rationaleMatch[1].trim();
        }
        
        // Clean the LLM response by removing score and rationale if they are only for internal use
        // or if they are not meant to be directly user-facing in the final response text.
        // For now, we assume the LLM might format them nicely, and we'll use the parsed values.
        // If the LLM response ALREADY contains the score/rationale clearly formatted,
        // we might just use that and not add our derived ones.
        // For robust parsing, we'll remove the matched parts from the LLM response to get clean response.
        if (scoreMatch) {
          const strippedScore = llmCleanResponse.replace(scoreMatch[0], '').trim();
          if (strippedScore) llmCleanResponse = strippedScore;
        }
        if (rationaleMatch) {
          const strippedRationale = llmCleanResponse.replace(rationaleMatch[0], '').trim();
          if (strippedRationale) llmCleanResponse = strippedRationale;
        }

      } catch (parseError) {
        logger.error('Error parsing score/rationale from LLM response', { error: parseError.message });
        // Fallback to policy-derived score/rationale if parsing fails
      }
    }

    // --- Consolidate Score and Rationale ---
    let finalScore = score; // Start with policy score
    let finalRationale = rationale; // Start with policy rationale

    if (llmGeneratedScore !== null) {
      // If LLM provided a score, use it. Maybe blend it? For now, prioritize LLM score if valid.
      finalScore = llmGeneratedScore;
    } else {
      // If LLM didn't provide a score, use policy score.
      // Add policy details to LLM rationale if LLM didn't provide rationale, or augment it.
      if (!llmGeneratedRationale) {
        finalRationale = `${rationale}. LLM did not provide specific rationale.`;
      } else {
        // Optionally, prepend or append policy rationale to LLM rationale
        // finalRationale = `${rationale}. LLM rationale: ${llmGeneratedRationale}`;
        finalRationale = llmGeneratedRationale; // Prioritize LLM's explanation if it's there
      }
    }
    
    // If the score is still 0 due to blocking, ensure rationale reflects that.
    if (finalScore === 0 && policyDecision !== 'BLOCK') {
        // This case might happen if LLM provided score 0 but policy was not BLOCK.
        // It's unlikely but worth considering.
    } else if (policyDecision === 'BLOCK' && finalScore > 0) {
        // If policy blocked, score should ideally be 0. Override if LLM incorrectly gave high score.
        finalScore = 0;
    }

    // Handle cases where content was redacted but not blocked
    if (policyDecision === 'REDACT' && !wasBlocked) {
      // The response text was already set to redacted_text.
      // The score reflects policy allowed action with redaction.
      // Rationale should reflect policy conditions and the fact of redaction.
      finalRationale = `Response redacted as per policy conditions: ${policyResult.conditions.join(', ')}. ${finalRationale}`;
    }

    // --- Final Response Assembly ---
    if (!wasBlocked) {
      // Use the cleaned LLM response if available, otherwise use the raw response or policy outcome text.
      finalResponse = llmCleanResponse || rawLlmResponse || finalResponse;
    }
    // If wasBlocked is true, finalResponse is already set by policyResult.reason or default.
    // We no longer append score/rationale to the user-facing response.


    // --- Developer Mode Output (Optional) ---
    // Include additional debugging info in dev mode
    if (devModeEnabled) {
      // This part might need to be handled by the caller (interactionService)
      // to format the full dev mode message. For now, just return core components.
    }

    return {
      finalResponse,
      wasBlocked,
      policyDecision,
      score: finalScore,
      rationale: finalRationale
    };
  }

  /**
   * Formats a detailed debugging message for developer mode.
   * 
   * @param {object} params - Debugging parameters.
   * @returns {string} - Formatted markdown message.
   */
  formatDevModeMessage(params) {
    const {
      request,
      inputPolicy,
      rawContext,
      curatedContext,
      prompt,
      rawResponse,
      finalResponse,
      policyResult,
      intentResult,
      totalLatencyMs,
      reasoning,
      authContext,
      policyInputDebug
    } = params;

    return `🔍 *[DEV MODE] Interaction Trace*
---
*Input:* ${request}
*Intent:* ${intentResult.industry}/${intentResult.intent} (conf: ${intentResult.confidence})
*Decision:* ${policyResult.decision}
*Rationale:* ${policyResult.reason || 'N/A'}
*Score:* ${POLICY_SCORE_MAP[policyResult.decision] || 0}/100

*Policy Details:*
- Conditions: ${policyResult.conditions?.join(', ') || 'None'}
- Rationale Code: ${policyResult.rationale_code || 'N/A'}

*Auth Context:*
- Role: ${authContext.userRole}
- Actor ID: ${authContext.actorId}
- Relationships: ${JSON.stringify(authContext.relationships || {}, null, 2)}

*LLM Reasoning (CoT):*
${reasoning || 'No reasoning provided.'}

*Performance:*
- Total Latency: ${totalLatencyMs}ms
`;
  }
}

module.exports = new ResponseComposer();
